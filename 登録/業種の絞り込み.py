NG_ALL_EXCEPT = {'不動産': r'比較|ランキング|ポータル|まとめ'}


def target():
    p = os.path.join(HERE, '集める業種.txt')
    if os.path.exists(p):
        t = [l.strip() for l in open(p, encoding='utf-8') if l.strip() and not l.startswith('#')]
        if t: return t
    return DEFAULT


TARGET = set(target())


def check(ind, text):
    """業種 ind・文字 text（広告主名・商品名・アカウント名・広告文・遷移先をつないだ物）で、集めるかを返す。(集めるか, 理由)"""
    if ind not in TARGET: return False, '集める業種ではない'
    if not re.search(HINT.get(ind, r'(?!)'), text, re.I): return False, '業種の言葉が無い'
    ng_all = NG_ALL
    if ind in NG_ALL_EXCEPT: ng_all = r'(?=a)b'  # 不動産は NG_ALL を使わない
    if re.search(ng_all, text, re.I): return False, '業種違いの言葉'
    if ind in NG_ALL_EXCEPT and re.search(NG_ALL_EXCEPT[ind], text, re.I): return False, '業種違いの言葉'
    if NG.get(ind) and re.search(NG[ind], text, re.I): return False, '業種違いの言葉'
    return True, ''
